export function praiseTagText(tag: string, lang: "en" | "id"): string {
  if (lang === "en") return tag;
  const m = tag.match(/^(.*) \((\d+) reviews\)$/);
  if (!m || !ID[m[1]]) return "";
  return `${ID[m[1]]} (${m[2]} ulasan)`;
}

export function praiseTagCaption(readAt: string, lang: "en" | "id"): string {
  return lang === "id"
    ? `Tag topik dari Google Maps. Angka = jumlah ulasan yang menyebut topik itu. Dibaca ${readAt}.`
    : `Topic tags from Google Maps. The number is reviews that mention the topic. Read ${readAt}.`;
}
