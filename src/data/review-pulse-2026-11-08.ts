// Google Maps review pulse collected 2026-11-08 (sort=newest, read-only).
// Method: current 3 months vs prior 3 months inside a 6-month window;
// relative dates stay month-precision, never invented days. A trend is
// stored as evidence only (per-half counts, averages and sentiment); the
// label is derived in code (reviewPulse.ts): diff = newerAvg - olderAvg,
// improving >= +0.3, worsening <= -0.3, else steady. Evidence is stored
// only when the minimum is met: 10+ dated reviews in the window AND 3+
// in each 3-month half; branches below the minimum have no trendEvidence
// and the card shows the not-enough-reviews fallback.
// Complaint themes come from real customer comment text only (owner
// responses excluded): the top 3 recurring keywords among reviews rated
// 3 stars or lower, each with its reviewer count.
//
// Coverage: 148 branches checked, 4 listings had no review list at their
// exact verified address (flagged, not collected): baby-jumper-gym-gading-serpong,
// gymboree-play-music-kelapa-gading, sparks-sports-academy-cibubur,
// sparks-sports-academy-sawangan. All 144 collected
// branches are venues in this repo and are keyed below (136 in
// venues.ts, 8 in venues-batch3.ts).
